import pytest

from fontokmai.feeds.road_names import clean_name, kind_of, names_in_text, search_key


@pytest.mark.parametrize(("raw", "clean", "key"), [
    ("ถนนสุขุมวิท", "สุขุมวิท", "สุขุมวิท"),
    ("ถ.พระราม 2", "พระราม 2", "พระราม2"),
    ("  สุขุมวิท 21(อโศก)", "สุขุมวิท 21", "สุขุมวิท21"),
    ("เพชรเกษม (ซอย 69 อินทาปัจ) (หนองแขม)", "เพชรเกษม", "เพชรเกษม"),
    ("เฉลิมพระเกียรติ ร.๙", "เฉลิมพระเกียรติ ร.9", "เฉลิมพระเกียรติร.9"),
    ("ซ.เพชรเกษม 42 *", "ซอยเพชรเกษม 42", "ซอยเพชรเกษม42"),
    ("ถนน", "", ""),
    ("ถนนรังสิต-นครนายก", "รังสิต-นครนายก", "รังสิตนครนายก"),
    ("Ratchadaphisek Rd", "Ratchadaphisek Rd", "ratchadaphisekrd"),
])
def test_clean_name_and_search_key(raw, clean, key):
    assert clean_name(raw) == clean
    assert search_key(raw) == key


def test_kind_follows_the_key_prefix():
    assert [kind_of(search_key(n)) for n in ("สุขุมวิท", "ซ.อารีย์", "อุโมงค์แยกดินแดง")] == ["road", "soi", "tunnel"]


@pytest.mark.parametrize(("title", "names"), [
    ("น้ำท่วม ถนนแจ้งวัฒนะ", ["แจ้งวัฒนะ"]),
    ("น้ำท่วม(น้ำทะเลหนุน) ถนนสุขสวัสดิ์", ["สุขสวัสดิ์"]),
    ("น้ำท่วม ถนนติวานนท์ ขาเข้า", ["ติวานนท์"]),
    ("น้ำท่วม ถนนพระราม 2 ขาออก", ["พระราม 2"]),
    ("น้ำท่วม ซอยสุขุมวิท 107 (ซอยแบริ่ง)", ["ซอยสุขุมวิท 107"]),
    ("น้ำท่วม ซอยกิ่งแก้ว 14/1", ["ซอยกิ่งแก้ว 14/1"]),
    ("น้ำท่วม อุโมงค์แยกดินแดง", ["อุโมงค์แยกดินแดง"]),
    ("น้ำท่วมผิวจราร ทางเข้าโรงผสมปูนปากเกร็ด ถนนติวานนท์", ["ติวานนท์"]),
    ("น้ำท่วม ถ.เพชรเกษม ซ.69", ["เพชรเกษม"]),
    ("น้ำท่วม ซอยวิภาวดีรังสิต 20 ถนนวิภาวดีรังสิต", ["ซอยวิภาวดีรังสิต 20", "วิภาวดีรังสิต"]),
    ("น้ำท่วม ถนนสุขุมวิท ถนนสุขุมวิท", ["สุขุมวิท"]),
    ("น้ำท่วม แขวงสีลม", []),
])
def test_names_in_text(title, names):
    assert names_in_text(title) == names
